%% Fourier fitting function
function [yFit, coefficients] = fourierFit(x, y, xFit)

    % Two-harmonic Fourier model:
    %
    % y = c0
    %   + c1*cos(2*pi*x/24) + s1*sin(2*pi*x/24)
    %   + c2*cos(4*pi*x/24) + s2*sin(4*pi*x/24)

    X = [ ...
        ones(size(x)), ...
        cos(2*pi*x/24), ...
        sin(2*pi*x/24), ...
        cos(4*pi*x/24), ...
        sin(4*pi*x/24)];

    % Least-squares solution
    coefficients = X \ y;

    % Evaluate fitted curve
