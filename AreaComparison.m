% Implement loops in this code to calculate it for different scenarios 

% Prepare Matlab
clc; clear; 


% System Inputs: % --------------------------------------------------------
% Component Temperatures
Tevap = 7;                              % Evaporator Temp [C]
Tabs = 40;                              % Absorber Temp [C]
Tcond = 40;                             % Condenser Temp [C]
Tgen = 90;                              % Generator Temp [C]

% Sizing Variables
area_ratio = [.1]';
A_data = 9290.304;                       % Data Center Area (m^2)
A_solar =  area_ratio .* A_data;                   % Solar Area (m^2)

q_data = 0.220;                           % Heat Gen. by Data Center per area (kW/m2)
q_solar = 23.9*10^3;                          % Avg energy from Solar per area per day (kWs/m2)


% Extra Variables
eta_HX = .80;                           % Solution Heat Exchanger Efficiency [100% -> 1]

% Determine Qload and Qgen
Qload = A_data * q_data;                % Cooling required by data center [kW]
Qgen = A_solar * q_solar;               % Avg energy generated by solar [kW]


% Simulate 1 day:
time = linspace(0,24,100)'; % Datapoints for Time of day in hours (1-24)
sun_start = 8; % Start Solar Time [hr]
sun_end = 17; % End Solar Time [hr]

% Assuming constant heat load, determine Qgen required by data center
[~, ~, ~, ~, ~, Q, ~] = LiBr_Absorption_solver(Tevap, Tabs, Tcond, Tgen, Qload,eta_HX, 'false');
Qgen_req(1:length(time),1) = Q(2);

% Determine Qgen produced by solar 
Qgen_prod = zeros(length(time),length(A_solar));
for i = 1:length(A_solar)
    for j = 1:length(time)
        if time(j) >= sun_start && time(j) <= sun_end
            Qgen_prod(j, i) = Qsolar_avg(Qgen(i), time(j), sun_start, sun_end, A_solar(i), 1); % Determine instantaneous solar input based [kW]
        else
            Qgen_prod(j, i) = 0;
        end
    end 
end

% Modify Qs based on heat recovery efficiency
eta_HXREC = 0.750;
Qgen_req = Qgen_req * (1-eta_HXREC);
Qgen_prod = Qgen_prod + Qgen_req*eta_HXREC;


plotting.Tyler5(1, time, [Qgen_req, Qgen_prod], area_ratio)